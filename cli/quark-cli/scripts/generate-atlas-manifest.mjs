#!/usr/bin/env node
/**
 * Walks monorepo `atlas/` and emits `src/templates/atlas/atlas-template-manifest.generated.ts`
 * so the Atlas tree is bundled like other string templates (compiled by tsc into `dist/`).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { createRequire } from "module";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const packageRoot = path.resolve(__dirname, "..");
const securityPkg = path.resolve(packageRoot, "../quark-security");
const securityDist = path.join(securityPkg, "dist");

if (!fs.existsSync(path.join(securityDist, "paths.js"))) {
    console.error(
        `[generate-atlas-manifest] Expected built @quark-hq/quark-security at ${securityDist}. Run: pnpm --filter @quark-hq/quark-security run build`
    );
    process.exit(1);
}

const require = createRequire(import.meta.url);
const { assertPathInsideRoot } = require(path.join(securityDist, "paths.js"));
const {
    existsSyncSafe,
    mkdirSyncSafe,
    readFileSafe,
    readdirWithFileTypesSafe,
    writeFileSafe,
} = require(path.join(securityDist, "fs.js"));

const SKIP_DIR_NAMES = new Set([
    "node_modules",
    ".next",
    ".git",
    "dist",
    "coverage",
    ".turbo",
    ".cache",
    "storybook-static",
    ".nx",
    ".yalc",
]);

const SKIP_FILE_NAMES = new Set([".DS_Store", "Thumbs.db"]);

/** @param {string} absolutePath @param {string} sourceRoot */
function shouldInclude(absolutePath, sourceRoot) {
    const rel = path.relative(sourceRoot, absolutePath);
    if (rel === "") return true;
    for (const seg of rel.split(path.sep)) {
        if (SKIP_DIR_NAMES.has(seg)) return false;
    }
    if (SKIP_FILE_NAMES.has(path.basename(absolutePath))) return false;
    return true;
}

/**
 * @param {string} dir
 * @param {string} sourceRoot
 * @param {{ relPosix: string, content: string }[]} out
 */
async function collectTextFiles(dir, sourceRoot, out) {
    // bearer:disable javascript_lang_path_traversal
    const safeDir = assertPathInsideRoot(sourceRoot, path.resolve(dir));
    const entries = await readdirWithFileTypesSafe(sourceRoot, safeDir);
    for (const ent of entries) {
        // bearer:disable javascript_lang_path_traversal
        const abs = assertPathInsideRoot(
            sourceRoot,
            path.join(safeDir, ent.name)
        );
        if (!shouldInclude(abs, sourceRoot)) continue;
        if (ent.isDirectory()) {
            await collectTextFiles(abs, sourceRoot, out);
        } else if (ent.isFile()) {
            const rel = path.relative(sourceRoot, abs);
            const relPosix = rel.split(path.sep).join("/");
            const content = await readFileSafe(sourceRoot, abs);
            out.push({ relPosix, content });
        }
    }
}

async function main() {
    const repoRoot = path.resolve(packageRoot, "../..");
    const atlasSource = path.join(repoRoot, "atlas");
    const outFile = path.join(
        packageRoot,
        "src",
        "templates",
        "atlas",
        "atlas-template-manifest.generated.ts"
    );

    if (!existsSyncSafe(repoRoot, atlasSource)) {
        console.error(
            `[generate-atlas-manifest] Source atlas not found at ${atlasSource}. Build from monorepo root with a top-level "atlas" app.`
        );
        process.exit(1);
    }

    /** @type {{ relPosix: string, content: string }[]} */
    const files = [];
    await collectTextFiles(atlasSource, atlasSource, files);
    files.sort((a, b) => a.relPosix.localeCompare(b.relPosix));

    const lines = [
        "/**",
        " * Auto-generated by scripts/generate-atlas-manifest.mjs — do not edit.",
        " */",
        "export const atlasTemplateFiles: Readonly<Record<string, string>> = {",
    ];
    for (const { relPosix, content } of files) {
        lines.push(`  ${JSON.stringify(relPosix)}: ${JSON.stringify(content)},`);
    }
    lines.push("};", "");

    mkdirSyncSafe(packageRoot, path.dirname(outFile), { recursive: true });
    await writeFileSafe(packageRoot, outFile, lines.join("\n"));
    console.log(
        `[generate-atlas-manifest] Wrote ${outFile} (${files.length} files)`
    );
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
